#!/usr/bin/env bash
# check-test-inventory.sh — "every test must run somewhere" gate.
#
# Fails when a *_test.go file's (path, build-tag) combination is not executed
# by any CI job / Make target. A test that never runs is worse than no test:
# it encodes false confidence and rots invisibly — the gateway e2e tests were
# profile-skipped locally and executed by NO CI job for months, and their
# first-ever execution (mid-upgrade, issue #58) surfaced four stale-assumption
# failures at once. This gate makes that class of drift a lint error.
#
# The map below mirrors the execution profiles wired in the Makefile and
# .github/workflows/ci-speed-proof.yml. When you add a new test directory or
# build tag, wire a job that runs it AND extend this map in the same PR.
set -euo pipefail
cd "$(dirname "$0")/.."

fail=0

# expected_tag <path> -> the //go:build expression class this path must carry
# so that its wired runner actually compiles it.
#
# Runners (keep in sync with Makefile targets + CI jobs):
#   (no tag)             -> `make test` (go test ./...)         [CI: test]
#   e2e                  -> `make test-e2e`                     [CI: test-e2e]
#   integration          -> `make test-integration`             [CI: test-integration]
#   acceptance           -> `make test-acceptance-parallel`     [CI: acceptance]
#   gateway_conformance  -> `make test-gateway-conformance`     [CI: test-gateway-conformance]
#   ingress_conformance  -> `make test-ingress-conformance`     [CI: test-ingress-conformance]
#   testinfra && unix    -> `make test-process`                [CI: test]
#   testinfra && linux   -> `make test-process` (tests/e2e/availability)
#   playground           -> `make test-playground`              [CI: test]

while IFS= read -r f; do
  # First //go:build line, stripped to the expression.
  tag="$(grep -m1 '^//go:build ' "$f" | sed 's|^//go:build ||' || true)"

  case "$f" in
    tests/process/process_integration_test.go)
      want="testinfra && unix" ;;
    tests/e2e/availability/*)
      # ptrace-based monitor tests: `make test-process`, never a cluster shard.
      want="testinfra && linux" ;;
    tests/e2e/*)
      want="e2e" ;;
    tests/integration/*)
      want="integration" ;;
    tests/agent/*)
      want="agentdocker" ;;
    tests/acceptance/*)
      want="acceptance" ;;
    tests/conformance/*)
      # Two suites share this directory; a file must be reachable from at
      # least one of them. Pure negations (e.g. `!ingress_conformance`)
      # are helper files compiled into the gateway suite.
      case "$tag" in
        *gateway_conformance*|*ingress_conformance*)
          continue ;;
        *)
          echo "UNWIRED: $f (tag: '${tag:-none}') — files under tests/conformance/ must carry gateway_conformance or ingress_conformance (or a negation of one) so a conformance job compiles them"
          fail=1; continue ;;
      esac ;;
    pkg/dataplane/parser/*|pkg/dataplane/validators/*|pkg/dataplane/validate_syntax_test.go|pkg/dataplane/validate_schema_test.go|pkg/generated/validators/*)
      # The client-native syntax + schema check the browser playground answers
      # `haproxy_valid` with. No production binary may link it, so it carries
      # the `playground` tag and `make test-playground` is its runner.
      want="playground" ;;
    *)
      # Unit tests (pkg/, cmd/, tests/*.go, scripts/…): run by `make test`
      # (plain `go test ./...`), which only compiles files whose build
      # expression is satisfied WITHOUT extra -tags. Negation-only
      # expressions (e.g. `!ignore_autogenerated`) satisfy that; any
      # positive custom tag means no runner ever compiles the file.
      case "$tag" in
        ""|'!'*)
          continue ;;
        race)
          # Toolchain-set tag: every -race run (make test) compiles it.
          continue ;;
        *)
          echo "UNWIRED: $f (tag: '$tag') — positive build tag outside tests/{e2e,integration,acceptance,conformance}; no Make target / CI job runs it. Wire a runner and extend scripts/check-test-inventory.sh."
          fail=1; continue ;;
      esac ;;
  esac

  # Directory with a single required tag: require exact match.
  if [ "$tag" != "$want" ]; then
    echo "UNWIRED: $f (tag: '${tag:-none}') — files under this directory must carry '//go:build $want' or the '$want' runner silently skips them"
    fail=1
  fi
done < <(git ls-files --cached --others --exclude-standard '*_test.go')

# CI runs tests/acceptance only through TestAllAcceptanceParallel, so every other
# top-level test must be one testEnv.Test(t, <feature>) call whose <feature>
# that runner lists.
acceptance_runner=tests/acceptance/parallel_test.go
mapfile -t acceptance_files < <(git ls-files --cached --others --exclude-standard 'tests/acceptance/*_test.go')
if [ "${#acceptance_files[@]}" -gt 0 ]; then
  if ! grep -qxF '    acceptance) make test-acceptance-parallel ;;' .github/scripts/run-remaining-suite.sh 2>/dev/null ||
    ! awk '/^test-acceptance-parallel:/ { recipe = 1; next }
      recipe && !/^\t/ { exit }
      recipe && index($0, "-run TestAllAcceptanceParallel ./tests/acceptance/...") { found = 1 }
      END { exit !found }' Makefile 2>/dev/null; then
    echo "UNREACHED: tests/acceptance — CI's acceptance suite no longer runs 'make test-acceptance-parallel' (-run TestAllAcceptanceParallel), so this check can't tell which tests CI runs. Update the acceptance section of scripts/check-test-inventory.sh to the new entry point."
    fail=1
  elif ! awk -v runner="$acceptance_runner" '
    function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
    FILENAME == runner && /^\tfeatures := \[\]types\.Feature\{$/ { listing = 1; found = 1; next }
    listing && /^\t\}$/ { listing = 0; next }
    listing {
      line = trim($0)
      if (line != "" && line !~ /^\/\//) { sub(/,$/, "", line); listed[line] = 1 }
      next
    }
    /^func Test[A-Za-z0-9_]*\(/ {
      name = $2; sub(/\(.*/, "", name)
      current = (name == "TestMain" || name == "TestAllAcceptanceParallel") ? "" : FILENAME ": " name
      if (current != "") order[++count] = current
      next
    }
    current != "" && /^}/ { current = ""; next }
    current != "" {
      line = trim($0)
      if (line != "" && line !~ /^\/\//) { statements[current]++; body[current] = line }
    }
    END {
      if (!found) {
        print "UNREACHED: " runner " — no \"features := []types.Feature{\" list in TestAllAcceptanceParallel, so no acceptance test is known to run in CI. Restore the list."
        exit 1
      }
      for (i = 1; i <= count; i++) {
        test = order[i]; feature = body[test]
        if (statements[test] == 1 && sub(/^testEnv\.Test\(t, /, "", feature) && sub(/\)$/, "", feature) && (feature in listed)) continue
        print "UNREACHED: " test " — CI runs only TestAllAcceptanceParallel, which does not run this test. Make its body one testEnv.Test(t, <feature>) call and add <feature> to the features list in " runner "."
        unreached = 1
      }
      exit unreached
    }' "${acceptance_files[@]}"; then
    fail=1
  fi
fi

if [ "$fail" -ne 0 ]; then
  echo ""
  echo "check-test-inventory: FAILED — every test must be compiled and run by the runner wired for its directory."
  exit 1
fi
echo "check-test-inventory: OK — every *_test.go file is wired to a runner."
